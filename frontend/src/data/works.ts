function s1(scores: Partial<Record<keyof typeof S1_WEIGHTS, number>>): ModuleContribution[] {
  return (Object.keys(S1_WEIGHTS) as (keyof typeof S1_WEIGHTS)[]).map((m) => ({
    module: m,
    score: scores[m] ?? 0,
    weight: S1_WEIGHTS[m],
  }))
}

function s2(scores: Partial<Record<keyof typeof S2_WEIGHTS, number>>): ModuleContribution[] {
  return (Object.keys(S2_WEIGHTS) as (keyof typeof S2_WEIGHTS)[]).map((m) => ({
    module: m,
    score: scores[m] ?? 0,
    weight: S2_WEIGHTS[m],
  }))
}

/** Composite is the weighted sum of module scores, shown in the breakdown panel. */
export function compositeOf(contributions: ModuleContribution[]): number {
  return Math.round(contributions.reduce((sum, c) => sum + c.score * c.weight, 0))
}


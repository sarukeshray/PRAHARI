/**
 * Severity is derived, never stored, so the chip on a row can never disagree
 * with the breakdown panel that explains it.
 *
 * The one departure from pure scoring is the compliance override: a rule
 * violation is a deterministic fact rather than a statistical inference, so any
 * COMPLIANCE finding lifts the work to at least HIGH regardless of where the
 * weighted score landed.
 */
export function severityFor(work: Omit<Work, 'severity'>): Severity {
  const tier = tierForScore(work.compositeScore)
  const hasCompliance = work.flags.some((f) => f.module === 'COMPLIANCE')
  if (hasCompliance && SEVERITY_RANK[tier] > SEVERITY_RANK.HIGH) return 'HIGH'
  return tier
}

/** True when the compliance override changed the tier the score alone produced. */
export function complianceOverrideApplied(work: Work): boolean {
  return work.severity !== tierForScore(work.compositeScore)
}

export const WORKS: Work[] = [...detailed, ...paddedWorks()].map((w) => {
  const scored = { ...w, compositeScore: compositeOf(w.contributions) }
  return { ...scored, severity: severityFor(scored) }
})

export function workById(id: string): Work | undefined {
  return WORKS.find((w) => w.workId === id)
}
